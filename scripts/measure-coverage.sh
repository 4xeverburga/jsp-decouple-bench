#!/usr/bin/env bash
# Measure dynamic code coverage of bench e2e flows with JaCoCo.
#
# Usage:
#   scripts/measure-coverage.sh <sample> <test> [<test>...]
#       e.g. measure-coverage.sh mamute vote-flow__upvote-increments-count
#            measure-coverage.sh openclinica subject-flow__subject-creation
#
# Per-test loop (each test gets a pristine stack and its own .exec):
#   1. reset the stack with the agent injected (mode from coverage.env:
#      compose -> coverage override; tomcat-local -> setenv.sh + restart)
#   2. run the flow via scripts/run_flow.py (flow.py is the single source of
#      truth; nothing test-specific lives here)
#   3. dump the .exec over JaCoCo's tcpserver channel (no JVM restart —
#      output=file races the next JVM's truncate-on-boot)
# Then: generate a CSV + HTML report per test and one aggregate report.
#
# Sample-specific knobs live in environments/<sample>/coverage.env; the JaCoCo
# jars are vendored in tools/jacoco/. Outputs go to coverage/<sample>/ (never
# under bench/ — that tree is read-only eval infrastructure).
set -euo pipefail

BENCH="$(cd "$(dirname "$0")/.." && pwd)"
cd "$BENCH"

if [ $# -lt 2 ]; then
  sed -n '2,14p' "$0"
  exit 1
fi
SAMPLE="$1"; shift
TESTS=("$@")

# --- sample config ------------------------------------------------------------
COV_ENV="environments/$SAMPLE/coverage.env"
[ -f "$COV_ENV" ] || { echo "missing $COV_ENV"; exit 1; }
# shellcheck disable=SC1090
source "$COV_ENV"
MODE="${COVERAGE_STACK_MODE:-compose}"

AGENT="tools/jacoco/jacocoagent.jar"
CLI="tools/jacoco/jacococli.jar"
[ -f "$AGENT" ] && [ -f "$CLI" ] || { echo "missing $AGENT/$CLI (vendor tools/jacoco/)"; exit 1; }

OUT="coverage/$SAMPLE"
mkdir -p "$OUT/exec"

JAVA_BIN="${JAVA_HOME:-/usr/lib/jvm/jdk-8.0.202-oracle-x64}/bin/java"
[ -x "$JAVA_BIN" ] || JAVA_BIN=java

AGENT_OPTS="output=tcpserver,address=*,port=${COVERAGE_AGENT_PORT:-6300}"

if [ "$MODE" = compose ]; then
  COMPOSE=(docker compose -f "environments/$SAMPLE/compose.yml" -f "environments/$SAMPLE/compose.coverage.yml")
  # some hosts need sg docker for group membership
  if ! docker info >/dev/null 2>&1; then
    COMPOSE=(sg docker -c "docker compose -f $BENCH/environments/$SAMPLE/compose.yml -f $BENCH/environments/$SAMPLE/compose.coverage.yml")
  fi

  # compose v5 `up --wait` exits 1 when a one-shot service exits (0), so wait
  # ourselves: app answers HTTP 200 AND every container is healthy or Exited (0)
  stack_ready() {
    curl -fsS -o /dev/null "$COVERAGE_BASE_URL/" || return 1
    "${COMPOSE[@]}" ps -a --format '{{.Status}}' | grep -qvE '^Up .*\((healthy)\)$|^Exited \(0\)' && return 1
    return 0
  }
  await_stack() {
    for _ in $(seq 1 150); do
      stack_ready && return 0
      sleep 2
    done
    echo "stack did not become ready"; return 1
  }

  reset_stack() {
    "${COMPOSE[@]}" down -v >/dev/null
    "${COMPOSE[@]}" up -d >/dev/null
    await_stack
  }
  classes_dir() {
    local dest="$OUT/classes"
    rm -rf "$dest"
    "${COMPOSE[@]}" cp "$COVERAGE_SERVICE:$COVERAGE_CONTAINER_CLASSFILES" "$dest"
    echo "$dest"
  }
else
  # tomcat-local: agent via $CATALINA_HOME/bin/setenv.sh (read by catalina.sh)
  TC="$COVERAGE_TOMCAT_HOME"
  SETENV="$TC/bin/setenv.sh"

  write_setenv() {
    mkdir -p "$TC/bin"
    cat > "$SETENV" <<EOF
# generated by scripts/measure-coverage.sh — coverage instrumentation only
CATALINA_OPTS="\$CATALINA_OPTS -javaagent:$BENCH/$AGENT=$AGENT_OPTS"
EOF
  }
  clear_setenv() {
    rm -f "$SETENV"
  }

  tomcat_up() {
    # never inherit the shell JAVA_HOME (machine default is JDK 21, which
    # breaks these Java 7 apps) — always pin JDK 8
    JAVA_HOME="${JDK8:-/usr/lib/jvm/jdk-8.0.202-oracle-x64}" \
      CATALINA_HOME="$TC" CATALINA_BASE="$TC" "$TC/bin/catalina.sh" start >/dev/null
    for _ in $(seq 1 100); do
      curl -fsS -o /dev/null --max-time 5 "$COVERAGE_BASE_URL/" && return 0
      sleep 3
    done
    echo "tomcat did not become ready"; return 1
  }

  tomcat_down() {
    "$TC/bin/catalina.sh" stop -force >/dev/null 2>&1 || true
    # wait until the HTTP port is actually released before starting again
    local port
    port="$(echo "$COVERAGE_BASE_URL" | sed -n 's#.*:\([0-9]*\)/.*#\1#p')"
    for _ in $(seq 1 30); do
      curl -s -o /dev/null --max-time 2 "localhost:$port" || return 0
      sleep 1
    done
    return 0
  }

  reset_stack() {
    # write the agent config BEFORE the reset: reset-pristine.sh itself
    # restarts Tomcat, so it comes back up already instrumented. Do NOT
    # stop/start again here — a second restart races the dying JVM's agent
    # socket (ServerSocket bind fails while the old one is still closing).
    write_setenv
    bash -c "$COVERAGE_RESET_CMD"
  }
  classes_dir() {
    echo "$COVERAGE_HOST_CLASSFILES"
  }
fi

# --- per-test loop ------------------------------------------------------------
for TEST in "${TESTS[@]}"; do
  echo "=== $SAMPLE/$TEST: pristine stack with agent ==="
  reset_stack

  echo "=== $SAMPLE/$TEST: running flow ==="
  .venv/bin/python scripts/run_flow.py "$SAMPLE" "$TEST"

  echo "=== $SAMPLE/$TEST: dumping exec (tcpserver) ==="
  dump_ok=0
  for _ in $(seq 1 10); do
    if "$JAVA_BIN" -jar "$CLI" dump --address localhost --port "${COVERAGE_AGENT_PORT:-6300}" \
         --destfile "$OUT/exec/$TEST.exec" --reset >/dev/null 2>&1; then
      dump_ok=1; break
    fi
    sleep 2
  done
  [ "$dump_ok" = 1 ] || { echo "could not dump coverage for $TEST"; exit 1; }
done

# --- reports -------------------------------------------------------------------
CLASSES="$(classes_dir)"
EXECS=()
for TEST in "${TESTS[@]}"; do
  EXECS+=("$OUT/exec/$TEST.exec")
done
SOURCEFILES=()
for SRC in ${COVERAGE_SOURCEFILES//:/ }; do
  SOURCEFILES+=(--sourcefiles "$BENCH/$SRC")
done
for TEST in "${TESTS[@]}"; do
  "$JAVA_BIN" -jar "$CLI" report "$OUT/exec/$TEST.exec" \
    --classfiles "$CLASSES" "${SOURCEFILES[@]}" \
    --csv "$OUT/$TEST.csv" --html "$OUT/html-$TEST" >/dev/null
done
"$JAVA_BIN" -jar "$CLI" report "${EXECS[@]}" \
  --classfiles "$CLASSES" "${SOURCEFILES[@]}" \
  --csv "$OUT/aggregate.csv" --html "$OUT/html-aggregate" >/dev/null

if [ "$MODE" = tomcat-local ]; then
  # leave the stack as the sample's normal e2e contract expects it
  tomcat_down
  clear_setenv
  tomcat_up
fi

echo "coverage reports: $OUT/{*.csv,html-*}"
